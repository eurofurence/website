        <strong>FAQ:</strong>
    </p>
    <div class="uk-column-1-2@l">
        <p>
            <strong>How many slots are there?</strong><br />
            There are a bit less than 50 slots each for the Dog and the Cat parts as well as close to 25 slots for the Fox part. Be fast as there might be more applications than slots.
        </p>

        <p>
            <strong>Do I need previous musical training?</strong><br />
            No. Everyone can join - as long as they are willing to practice. That includes absolute beginners, especially for the "Cat" or "Dog" parts. The "Fox" parts are slightly more technical and aimed at people with some experience in keeping time.
        </p>

        <p>
            <strong>Do I need my own drum?</strong><br />
            Drums are provided. However, you are asked to buy your own set of wooden drumsticks (called "bachi").
            They can be picked at the Con Store at the cost of 20 Euros (participants only).
            After the show, you can keep them as a souvenir.
        </p>

        <p>
            <strong>How do I practice at home?</strong><br />
            Instructional videos by the TAIKO BASTARDS will be made available. You can play along and practice the rhythms at home. You can use any drumstick-shaped objects to practice - for example wooden spoons. 
        </p>

        <p>
            <strong>Is it possible to perform in fursuit?</strong><br />
            Yes. Playing in fursuit does add another layer of difficulty. But it is possible if you have enough range of motion, visibility and dexterity in suit. In doubt, this can be tested and decided during the workshop. As stage space is very limited, please don't bring suits with a large, bulky tail or wings.
        </p>

        <p>
            <strong>I'm interested. But what if I have further questions?</strong><br />
            All participants will be invited to a Telegram chat where questions about practice and technique as well as organisational matters can be adressed.
        </p>
