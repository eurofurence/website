<p>
    The Eurofurence Theming and Experience Team designs one of Europe’s largest furry conventions. The team consists of dedicated volunteers who perform a wide range of tasks. Among other things, their responsibilities include developing the theming guidelines, designing the public convention space, setting up AV equipment for decorative purposes, furnishing the public convention space, and developing the wayfinding system in collaboration with other departments. <br />
    We aim to create a pleasant and theme-specific atmosphere for our guests.<br />
    To this end, we are looking for another lighting technician to join our existing team and help us create an unforgettable experience for our attendees. As part of our team, you will primarily work alongside our current technician to plan, set up, program, and dismantle the lighting design.
</p>

<h3>What you will do</h3>
<ul>
    <li>Coordinate our team of graphic designers, assign tasks, and set internal deadlines with proper buffers.</li>
    <li>Manage print production for everything from large-format venue graphics (banners, flags, escalator stickers, hall signs) to smaller print items.</li>
    <li>Check incoming design files for correct print specs like bleed, CMYK color profiles, resolution, and formats before sending them to production.</li>
    <li>Work directly with print vendors based in Germany, decide on material orders, send print files on time, and schedule delivery and installation.</li>
    <li>Stay in touch with volunteer artists who donate artwork to the convention, keep communication appreciative and friendly, answer questions, and track deadlines.</li>
	<li>Decide where graphics and visual elements are placed throughout the venue, with plenty of room to bring in your own creative ideas.</li>
</ul>

<h3>What we are looking for</h3>
<ul>
    <li>Fluent German, as you will need to communicate and negotiate directly with suppliers based in Germany.</li>
    <li>Good English skills for internal team chat and communicating with international artists.</li>
    <li>Agency experience or a solid background in graphic design and print prepress.</li>
	<li>Confidence using industry-standard tools like Adobe Photoshop, Illustrator, and InDesign (or Affinity suite equivalents).</li>
	<li>Good knowledge of common vector and pixel file formats, as well as print data requirements for small and large-format items.</li>
	<li>Strong organizational skills to manage deadlines, plan buffers, and keep projects moving.</li>
	<li>An appreciative and supportive attitude when working with staff and volunteer artists.</li>
</ul>

<h3>Good to know</h3>
