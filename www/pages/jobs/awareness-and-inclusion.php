<p>Are you passionate about fostering a safe, welcoming, and inclusive convention experience for all attendees – especially those amongst marginalized groups, with disabilities or accessibility needs, and from vulnerable backgrounds? Do you have strong interpersonal skills, a calm demeanor, and a genuine desire to assist others in times of need? If so, we wholeheartedly invite you to volunteer for the Awareness & Inclusion Team!</p>
<p>
    <strong>What Does the Awareness & Inclusion Team Do?</strong><br />
    Our vision for a truly inclusive and accessible convention is one where each and every attendee feels (and is) safe, welcomed, and valued. As a department, we see ourselves as a pivotal interface between other staff departments, security, and attendees. In this position, we aim to create an environment where barriers – whether disability-based, social, or emotional - are actively addressed in a warm and helpful manner, ensuring that everyone, regardless of background or ability, can fully participate in and enjoy Eurofurence. 
</p>
<p>
    <strong>Why Join Awareness & Inclusion:</strong><br />
    To be part of Awareness & Inclusion is to be actively ‘doing something’ against discrimination, accessibility limitations, and safety concerns of all kinds during Eurofurence.
</p>
    
<p>
    <strong>Example Staff Responsibilities:</strong>
</p>

<strong>On-Site During the Convention –</strong>
<ul>
    <li>Serve as a point of trust and offer support and resources to those experiencing accessibility issues, harassment, emotional distress, or conflict. Respond to and de-escalate interpersonal issues in public or private settings. </li>
    <li>Distribute informational materials, i.e. flyers, covering awareness and accessibility issues</li>
    <li>Monitor and support health supplies and above all the Quiet Room – ensuring that that the space remains calm and safe for individuals needing sensory relief or a break.</li>
    <li>Actively work alongside convention security and staff to ensure a safe and enjoyable experience for all.</li>
</ul>

<strong>Pre- and Post-Convention –</strong>
<ul>
    <li>Improve and update team policies, training materials, manuals, and public handouts based on feedback from the team, other branches of staff, and attendees.</li>
    <li>Produce posters, fliers, and social media posts to increase visibility for both Awareness & Inclusion team initiatives and related issues, as well as recruitment materials.</li>
    <li>Organize and increase the visibility of feedback mechanism before and during the con, before documenting and implementing results post-con</li>
    <li>Work directly with other departments to supply input and resources on accessibility, awareness, and safety necessities.</li>
</ul>

<p>And much more – if you have a specific skillset or idea that you feel would work well within our team or could contribute towards awareness and inclusion issues, see the end of this listing for ways to get in contact with us.</p>

<strong>What We’re Looking For:</strong>
<ul>
    <li>Strong communication and active listening skills.</li>
    <li>Ability to remain calm and level-headed in sensitive or stressful situations.</li>
    <li>A friendly and approachable attitude.</li>
    <li>Discretion and professionalism when handling personal, sensitive, or delicate matters.</li>
    <li>A dedication to Eurofurence’s values, especially inclusivity, safety, and mutual respect.</li>
    <li>Previous experience in mediation, crisis intervention, accessibility work, or similar fields is a large plus, but not required. Training will be given!</li>
</ul>
<p>
    <strong>All Volunteers are Welcome</strong> – we strive to make our team accessible to all, not including, but rather especially for those with disabilities and neurodivergencies. If you have accessibility needs or concerns about certain responsibilities, we will work with you to ensure that you can contribute fully to the team and that it serves as a welcoming, friendly place.
</p>
