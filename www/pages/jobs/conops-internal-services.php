<p>Internal Services is the glue that holds the convention together, behind the scenes and sometimes right in front of them. This is where you'll find the tasks that don't fit neatly into one box, and that's exactly what makes it exciting.</p>

<p><strong>Seating Service:</strong> Our hard-working staff sometimes has shifts right up until a popular show starts. The Seating Service makes sure they don't have to stress about finding a seat. You'll be managing and distributing reserved seats so team members can go straight from their shift to the show.</p>

<p><strong>On Duty Team:</strong> Our very own special task group. Whether a department needs an extra pair of hands, something unexpected comes up, or a task needs doing that nobody else covers, the On Duty Team is there. Always ready, always flexible. No two shifts are the same, and you'll get to see parts of the convention most people never do.</p>

<p>Being fluent in English is mandatory for this position. No specific skills required, we'll find the right tasks for you.</p>

<p>We provide manuals and process documentation for all positions. Experienced team members ("Council") and a Director on Duty are always available to help you during the convention.</p>

<p>While this ad is for Internal Services, joining ConOps means you become part of the whole team. We encourage everyone to try different roles, you can pick your shifts across all our services using our self-scheduling tool. You're in control of your schedule. Pick the shifts that work for you, and we only step in if shifts still need filling. We expect around 4-5 hours per day you're at the convention, typically adding up to about 15-20 hours across the convention days (Wednesday to Saturday).</p>

<p>We ask our team members to arrive by Tuesday morning to help with setup and to be available on Sunday for teardown. Setup and teardown are an all-hands effort: regardless of your usual role, everyone pitches in. How much you contribute on those days is up to you, every pair of hands helps!</p>

<p>You must be a registered attendee of Eurofurence and meet the convention's minimum age requirement. No prior experience is needed. There is no application deadline, you can reach out to us at any time. We'll have a short, informal chat to get to know each other and figure out where you'd fit best.</p>

