<h3>Who are we?</h3>

<p>The Programming Team creates the core of the Eurofurence experience. Our mission is to make Eurofurence the most interesting and entertaining furry convention possible while supporting the many different cultural aspects of the furry fandom.</p>

<p>We coordinate a diverse event schedule and work together with panelists and many other convention departments to bring hundreds of activities to life throughout the convention.</p>

<h3>Your Job</h3>

<p>As an Event Coordinator, you take ownership of larger or more complex events and help guide them from idea to execution.</p>

<p>Your tasks may include:</p>
<ul>
    <li>Coordinating events with panelists and convention teams</li>
    <li>Acting as the main contact person for assigned events</li>
    <li>Helping schedule and organize event logistics</li>
    <li>Solving issues and adapting to changes during the convention</li>
    <li>Coming up with new and unique event ideas</li>
</ul>
<p>We are looking for people who:</p>
<ul>
    <li>Are organized and proactive</li>
    <li>Communicate clearly and professionally</li>
    <li>Enjoy coordinating projects and people</li>
    <li>Stay calm and flexible in dynamic situations</li>
</ul>
<p>Previous organizational or project coordination experience is helpful, but not required.</p>

