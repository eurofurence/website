<p>
    At Eurofurence, the theming department plays a crucial role in setting the atmosphere and aesthetic of the entire convention. Their main responsibility is to design and create the visual ambiance throughout the event spaces, making sure everything looks engaging, fun, and immersive for the attendees. <br />
    This includes bringing the theme to life as each year Eurofurence has a different theme.<br />
</p>

<h3>Your Responsibilities</h3>
<ul>
    <li>This role is exclusive to the preparation phase before the convention, requiring availability between April and August.</li>
    <li>Design and prepare print-ready files for large format materials, including banners, signs, flags, standees, escalator stickers, and other media for various use cases.</li>
    <li>This position requires both creativity and technical expertise.</li>
    <li>Coordinate file submission to our printer, if necessary, communicate any adjustments or revisions required.</li>
</ul>

<h3>Your Profile</h3>
<ul>
    <li>Highly reliable and able to meet deadlines consistently.</li>
    <li>Preferably, you have a background in design or have completed a design-related apprenticeship.</li>
    <li>Experience in the industry, whether through agency work or freelance, is a plus, but not a requirement. </li>
    <li>If you're self-taught and passionate about design with a willingness to learn, we'd love to hear from you.</li>
    <li>Familiarity with PDFs and color profiles is essential. Terms like “vector graphics” and “CMYK” should be familiar to you.</li>
    <li>Experience in large format printing and working with a variety of materials and techniques (e.g. contour cut lines, spot colours...) is required.</li>
    <li>Proficiency in Adobe InDesign, Illustrator, and Photoshop, or similar graphic design programs, is expected.</li>
</ul>

