<p>At the Locker Service, you will be in direct contact with our attendees. You will be taking care of personal belongings: bags, backpacks, and other items that attendees want to store while they explore the convention, visit the Dealers' Den, browse the Art Show, or simply walk around without carrying everything. Think of it as Tetris, but you also need to find the blocks again!</p>

<p>Being fluent in English is mandatory for this position.</p>

<p>No prior experience is needed. We provide manuals and process documentation for all positions. Experienced team members ("Council") and a Director on Duty are always available to help you during the convention.</p>

<p>While this ad is for the Locker Service, joining ConOps means you become part of the whole team. We encourage everyone to try different roles, you can pick your shifts across all our services using our self-scheduling tool. You're in control of your schedule. Pick the shifts that work for you, and we only step in if shifts still need filling. We expect around 4-5 hours per day you're at the convention, typically adding up to about 15-20 hours across the convention days (Wednesday to Saturday).</p>

<p>We ask our team members to arrive by Tuesday morning to help with setup and to be available on Sunday for teardown. Setup and teardown are an all-hands effort: regardless of your usual role, everyone pitches in. How much you contribute on those days is up to you, every pair of hands helps!</p>

<p>You must be a registered attendee of Eurofurence and meet the convention's minimum age requirement. There is no application deadline, you can reach out to us at any time. We'll have a short, informal chat to get to know each other and figure out where you'd fit best.</p>

