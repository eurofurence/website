<h3>Who are we?</h3>

<p>The Programming Team creates the core of the Eurofurence experience. Our mission is to make Eurofurence the most interesting and entertaining furry convention possible while supporting the many different cultural aspects of the furry fandom.</p>
<p>We plan and coordinate panels, shows, games, workshops, and other activities that make Eurofurence feel alive. We work closely with panelists, stage crew, logistics, video, and other convention teams to ensure events run smoothly from planning to execution.</p>

<h3>Your Job</h3>

<p>As part of the Event Team, you help shape the convention programme and support the event planning process</p>

<p>Your tasks may include:</p>
<ul>
    <li>Monitoring the ticket system for new event submissions</li>
    <li>Collecting and reviewing event ideas</li>
    <li>Helping improve and expand the convention programme</li>
    <li>Coming up with new and unique event ideas</li>
    <li>(Optional) Supporting the team during convention operations onsite</li>
</ul>

<p>We are looking for people who:</p>
<ul>
    <li>Enjoy working with others</li>
    <li>Have good communication skills</li>
    <li>Are reliable and organized</li>
    <li>Are interested in helping create memorable convention experiences</li>
</ul>

<p>No previous convention staff experience is required - motivation and teamwork matter most.</p>

