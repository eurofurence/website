function efParseGermanTime(string $iso): DateTimeImmutable {
    return (new DateTimeImmutable($iso))->setTimezone(new DateTimeZone('Europe/Berlin'));
}

function efFormatNightRange(string $startIso, string $endIso): string {
    $start = efParseGermanTime($startIso);
    $end = efParseGermanTime($endIso);
    return sprintf('%s %s - %s %s', $start->format('D'), $start->format('H:i'), $end->format('H:i'), $start->format('T'));
}

function efFormatSetRange(string $startIso, string $endIso): string {
    $start = efParseGermanTime($startIso);
    $end = efParseGermanTime($endIso);
    return sprintf('%s - %s', $start->format('H:i'), $end->format('H:i'));
}

