<script>
    (() => {
        const timeBlocks = document.querySelectorAll('.js-time-convert');
        if (!timeBlocks.length) {
            return;
        }

        const localDayTimeFormatter = new Intl.DateTimeFormat(undefined, {
            weekday: 'short',
            hour: '2-digit',
            minute: '2-digit'
        });

        const zoneFormatter = new Intl.DateTimeFormat(undefined, {
            timeZoneName: 'short'
        });

        const getZoneName = (date) => {
            const zonePart = zoneFormatter.formatToParts(date).find((part) => part.type === 'timeZoneName');
            return zonePart ? zonePart.value : '';
        };

        timeBlocks.forEach((timeBlock) => {
            const startRaw = timeBlock.getAttribute('data-start');
            const endRaw = timeBlock.getAttribute('data-end');
            if (!startRaw || !endRaw) {
                return;
            }

            const start = new Date(startRaw);
            const end = new Date(endRaw);
            if (Number.isNaN(start.getTime()) || Number.isNaN(end.getTime())) {
                return;
            }

            const startText = localDayTimeFormatter.format(start);
            const endText = localDayTimeFormatter.format(end);
            const zoneName = getZoneName(start);
            const localTimeText = `${startText} - ${endText}`;
            const tooltipText = `Local time${zoneName ? " (" + zoneName + ")" : ""}:<br/>${localTimeText}`;
            timeBlock.setAttribute('title', tooltipText);
        });
    })();
</script>
