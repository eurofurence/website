<section>
  <h2>Requirements & Training</h2>
  <p>Most Critter tasks do not require any special qualifications. You can simply pick the shifts that match your time and energy..</p>
  <p>Some tasks, such as stage work or roles involving safety and health responsibilities, require a certification before you can join. Certifications are provided through short safety briefings or training sessions or have to be obtained before the convention. These will be clearly listed in the Critter System along with the dates and times. If you are interested in these tasks, please complete the certification first so that everything runs safely and smoothly. If a certification only has to be verified for a department, ask the Critter Operations Team at the Eurofurence Info Desk for assistance.</p>
</section>

<section>
  <h2>Critter Rewards</h2>
  <p>Every hour you contribute as a Critter counts. To thank you for your time and energy, you can collect Critter Rewards based on your hours of volunteering. Rewards can be verified and picked up at the Eurofurence Info Desk from the Critter Operations Team.</p>
  <p>Examples of rewards include:</p>
  <ul>
    <li>The Volunteer Button after your first two hours</li>
    <li>Priority Access Tickets for select events</li>
    <li>Stickers, bookmarks, postcards and other collectibles</li>
    <li>Entry into the Critter Art Raffle with the chance to win unique artwork</li>
  </ul>
  <p>The more hours you give, the more rewards you get. All items are limited.</p>
</section>

<section>
  <h2>Support and Information</h2>
