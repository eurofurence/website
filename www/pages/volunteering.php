  <p>Whether you have questions about the <strong>Critter System</strong>, your shifts, or anything else related to volunteering at Eurofurence, our team is here to help. <strong>The Info Desk is open daily from Wednesday to Saturday, 9:00 until midnight</strong>. Feel free to come by at any time!</p>
</section>

